function handleContactSubmit(event) {
  event.preventDefault();
  const form = event.currentTarget;
  const formData = new FormData(form);
  const name = (formData.get('name') || '').toString().trim();
  const email = (formData.get('email') || '').toString().trim();
  const message = (formData.get('message') || '').toString().trim();
  const subject = encodeURIComponent(`Neue Anfrage von ${name || 'Unbekannt'}`);
  const body = encodeURIComponent(`Name: ${name}\nE-Mail: ${email}\n\nNachricht:\n${message}`);
  window.location.href = `mailto:${EMAIL}?subject=${subject}&body=${body}`;

  const status = document.getElementById('form-status');
  if (status) {
    const tx = TRANSLATIONS[currentLang];
    status.textContent = tx['contact.formStatusSent'] || 'Your message will open in your email application.';
  }
  form.reset();
}

